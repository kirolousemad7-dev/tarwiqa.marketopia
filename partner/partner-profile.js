function getPartnerMaids() {
    const created = loadJson("createdMaids", []);
    const overrides = loadJson("maidProfileOverrides", {});
    return [...defaultMaids, ...created]
        .map((maid) => ({ ...maid, ...(overrides[maid.id] || {}) }))
        .filter(
            (maid, index, all) =>
                all.findIndex((item) => item.id === maid.id) === index,
        )
        .filter((maid) => maid.operatorId === partner.id);
}

function upcomingOrders() {
    return scopedOrders
        .filter((order) => parseDateOnly(order.arrivalDate) >= getToday())
        .sort((a, b) => a.arrivalDate.localeCompare(b.arrivalDate));
}
function maidProfit(maid) {
    return (
        (Number(maid.doneOrders) || 0) * 35 + (Number(maid.salary) || 0) * 0.08
    );
}
function partnerProfit() {
    return scopedOrders.reduce(
        (sum, order) => sum + order.amountValue * 0.18,
        0,
    );
}
function showToast(message) {
    const toast = q("partnerProfileToast");
    toast.textContent = message;
    toast.classList.remove("hidden");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toast.classList.add("hidden"), 2800);
}

