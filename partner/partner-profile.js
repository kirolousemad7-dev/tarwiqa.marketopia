function loadJson(key, fallback) {
    try {
        return JSON.parse(localStorage.getItem(key)) ?? fallback;
    } catch (error) {
        return fallback;
    }
}
function saveJson(key, value) {
    localStorage.setItem(key, JSON.stringify(value));
}
function escapeHtml(value) {
    return String(value).replace(
        /[&<>"']/g,
        (character) =>
            ({
                "&": "&amp;",
                "<": "&lt;",
                ">": "&gt;",
                '"': "&quot;",
                "'": "&#39;",
            })[character],
    );
}
function money(value) {
    return new Intl.NumberFormat("en-EG", {
        style: "currency",
        currency: "EGP",
        maximumFractionDigits: 0,
    }).format(Number(value) || 0);
}
function parseDateOnly(value) {
    const [year, month, day] = value.split("-").map(Number);
    return new Date(year, month - 1, day);
}
function getToday() {
    const override = localStorage.getItem("partnerDashboardToday");
    const today = override ? parseDateOnly(override) : new Date();
    today.setHours(0, 0, 0, 0);
    return today;
}
function formatDate(value) {
    const [year, month, day] = value.split("-");
    return `${day}-${month}-${year}`;
}
function initials(name) {
    return name
        .split(/\s+/)
        .filter(Boolean)
        .slice(0, 2)
        .map((part) => part[0].toUpperCase())
        .join("");
}
function statusLabel(value) {
    return String(value).charAt(0).toUpperCase() + String(value).slice(1);
}

function resolvePartner() {
    const session = loadJson("tarwiqaPartnerSession", null);
    const createdPartners = loadJson("createdPartners", []);
    const availablePartners = [...partners, ...createdPartners].filter(
        (item, index, all) =>
            all.findIndex((partnerItem) => partnerItem.id === item.id) ===
            index,
    );
    const requestedId =
        params.get("partnerId") ||
        session?.partnerId ||
        availablePartners[0].id;
    const base =
        availablePartners.find((item) => item.id === requestedId) ||
        availablePartners[0];
    return {
        ...base,
        ...(session?.partnerId === base.id ? session : {}),
        id: base.id,
        zone:
            session?.workZone ||
            base.zone ||
            base.workZones?.[0] ||
            "Not assigned",
        managedMaids: Number(
            base.managedMaids ?? base.assignedMaidIds?.length ?? 0,
        ),
        completedOrders: Number(base.completedOrders || 0),
        shift:
            base.shift ||
            `${base.workingHours?.start || "08:00"} - ${base.workingHours?.end || "20:00"}`,
    };
}

