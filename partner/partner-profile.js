function profileT(key) {
    return (
        partnerProfileTranslations[partnerProfileLanguage]?.[key] ||
        partnerProfileTranslations.en[key] ||
        key
    );
}
function applyPartnerProfileLanguage() {
    document.documentElement.lang = partnerProfileLanguage;
    document.documentElement.dir =
        partnerProfileLanguage === "ar" ? "rtl" : "ltr";
    document.body.classList.toggle("rtl", partnerProfileLanguage === "ar");
    document.querySelectorAll("[data-i18n]").forEach((node) => {
        node.textContent = profileT(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
        node.placeholder = profileT(node.dataset.i18nPlaceholder);
    });
    document.getElementById("profileLanguageToggleBtn").textContent =
        profileT("languageButton");
    document.querySelectorAll("table").forEach((table) => {
        const keys =
            table.closest(".profile-card")?.textContent.includes("Orders") ||
            table.closest(".profile-card")?.textContent.includes("طلبات")
                ? [
                      "order",
                      "arrivalDate",
                      "arrivalTime",
                      "offer",
                      "amount",
                      "maid",
                  ]
                : [
                      "maid",
                      "status",
                      "salary",
                      "doneOrders",
                      "estimatedProfit",
                      "profile",
                  ];
        table.querySelectorAll("th").forEach((th, index) => {
            th.textContent = profileT(keys[index]);
        });
    });
    document.querySelectorAll(".maid-link").forEach((link) => {
        link.textContent = profileT("viewMaid");
    });
}
